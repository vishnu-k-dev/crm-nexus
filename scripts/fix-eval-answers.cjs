const fs = require("fs");
const path = require("path");

const DATA = path.join(__dirname, "../data/crm");
const questions = JSON.parse(fs.readFileSync(path.join(DATA,"eval_questions.json"),"utf8"));
const customers = JSON.parse(fs.readFileSync(path.join(DATA,"customers.json"),"utf8"));
const outages = JSON.parse(fs.readFileSync(path.join(DATA,"outages.json"),"utf8"));
const vendors = JSON.parse(fs.readFileSync(path.join(DATA,"vendors.json"),"utf8"));
const regions = JSON.parse(fs.readFileSync(path.join(DATA,"regions.json"),"utf8"));
const employees = JSON.parse(fs.readFileSync(path.join(DATA,"employees.json"),"utf8"));
const compliance = JSON.parse(fs.readFileSync(path.join(DATA,"compliance.json"),"utf8"));
const tickets = JSON.parse(fs.readFileSync(path.join(DATA,"tickets.json"),"utf8"));
const projects = JSON.parse(fs.readFileSync(path.join(DATA,"projects.json"),"utf8"));

const custById = Object.fromEntries(customers.map(c=>[c.id,c]));
const outageById = Object.fromEntries(outages.map(o=>[o.id,o]));
const vendById = Object.fromEntries(vendors.map(v=>[v.id,v]));
const empById = Object.fromEntries(employees.map(e=>[e.id,e]));
const regionById = Object.fromEntries(regions.map(r=>[r.id,r]));
const compById = Object.fromEntries(compliance.map(c=>[c.id,c]));
const projById = Object.fromEntries(projects.map(p=>[p.id,p]));

let wrong = 0;
const newQ = questions.map((q, i) => {
  const t = q.question;
  let m, expected;

  if (m = t.match(/severity level of outage (OUTAGE-\d+)/)) {
    const o = outageById[m[1]];
    expected = "Outage " + m[1] + " has severity " + (o ? o.severity : "UNKNOWN") + ".";
  } else if (m = t.match(/duration.*outage (OUTAGE-\d+)/)) {
    const o = outageById[m[1]];
    expected = "Outage " + m[1] + " lasted " + (o ? o.duration_hrs : "UNKNOWN") + " hours.";
  } else if (m = t.match(/which vendor.*responsible.*outage (OUTAGE-\d+)/)) {
    const o = outageById[m[1]]; const v = o ? vendById[o.vendor_id] : null;
    expected = "Outage " + m[1] + " was caused by vendor " + (o ? o.vendor_id : "UNKNOWN") + (v ? " (" + v.name + ")" : "") + ".";
  } else if (m = t.match(/which region.*outage (OUTAGE-\d+)/)) {
    const o = outageById[m[1]]; const r = o ? regionById[o.region_id] : null;
    expected = "Outage " + m[1] + " occurred in " + (o ? o.region_id : "UNKNOWN") + (r ? " (" + r.name + ")" : "") + ".";
  } else if (m = t.match(/health status.*customer (CUST-\d+)/)) {
    const c = custById[m[1]];
    expected = "Customer " + m[1] + " has health status " + (c ? c.health_label : "UNKNOWN") + " with a score of " + (c ? c.health_score : "UNKNOWN") + "/100.";
  } else if (m = t.match(/primary vendor.*customer (CUST-\d+)/)) {
    const c = custById[m[1]]; const v = c ? vendById[c.primary_vendor_id] : null;
    expected = "Customer " + m[1] + "'s primary vendor is " + (c ? c.primary_vendor_id : "UNKNOWN") + (v ? " (" + v.name + ")" : "") + ".";
  } else if (m = t.match(/annual recurring revenue.*customer (CUST-\d+)/)) {
    const c = custById[m[1]];
    expected = "Customer " + m[1] + " has an ARR of $" + (c ? c.arr_usd.toLocaleString() : "UNKNOWN") + ".";
  } else if (m = t.match(/SLA tier.*vendor (VEND-\d+)/)) {
    const v = vendById[m[1]];
    expected = "The SLA tier for " + m[1] + (v ? " (" + v.name + ")" : "") + " is " + (v ? v.sla_tier : "UNKNOWN") + ".";
  } else if (m = t.match(/role.*department.*employee (EMP-\d+)/)) {
    const e = empById[m[1]];
    expected = "Employee " + m[1] + (e ? " (" + e.name + ")" : "") + " is a " + (e ? e.role : "UNKNOWN") + " in the " + (e ? e.department : "UNKNOWN") + " department.";
  } else if (m = t.match(/which region.*employee (EMP-\d+)/)) {
    const e = empById[m[1]];
    expected = "Employee " + m[1] + (e ? " (" + e.name + ")" : "") + " operates in " + (e ? e.region_id : "UNKNOWN") + ".";
  } else if (m = t.match(/how many customers.*impacted by (OUTAGE-\d+)/)) {
    const o = outageById[m[1]];
    if (o) {
      const cnt = customers.filter(c => c.primary_vendor_id === o.vendor_id && c.region_id === o.region_id).length;
      const v = vendById[o.vendor_id]; const r = regionById[o.region_id];
      expected = cnt + " customers were directly impacted by " + m[1] + ". These customers depend on " + o.vendor_id + (v ? " (" + v.name + ")" : "") + " and are hosted in " + o.region_id + (r ? " (" + r.name + ")" : "") + ".";
    }
  } else if (m = t.match(/how many tickets.*generated by (OUTAGE-\d+)/)) {
    const cnt = tickets.filter(t => t.outage_id === m[1]).length;
    expected = "Outage " + m[1] + " generated " + cnt + " support tickets.";
  } else if (m = t.match(/how many compliance cases.*triggered by (OUTAGE-\d+)/)) {
    const cnt = compliance.filter(c => c.outage_id === m[1]).length;
    expected = "Outage " + m[1] + " triggered " + cnt + " compliance cases.";
  } else if (m = t.match(/how many customers.*primary dependency on (VEND-\d+)/)) {
    const cnt = customers.filter(c => c.primary_vendor_id === m[1]).length;
    const v = vendById[m[1]];
    expected = "Vendor " + m[1] + (v ? " (" + v.name + ")" : "") + " has " + cnt + " customers as primary dependency.";
  } else if (m = t.match(/how many compliance cases.*associated with vendor (VEND-\d+)/)) {
    const cnt = compliance.filter(c => c.vendor_id === m[1]).length;
    expected = "Vendor " + m[1] + " is associated with " + cnt + " compliance cases.";
  } else if (m = t.match(/how many customers.*hosted in (REGION-[A-Z-]+)/)) {
    const cnt = customers.filter(c => c.region_id === m[1]).length;
    const r = regionById[m[1]];
    expected = "Region " + m[1] + (r ? " (" + r.name + ")" : "") + " hosts " + cnt + " customers.";
  } else if (m = t.match(/how many outages.*occurred in (REGION-[A-Z-]+)/)) {
    const cnt = outages.filter(o => o.region_id === m[1]).length;
    const r = regionById[m[1]];
    expected = "Region " + m[1] + (r ? " (" + r.name + ")" : "") + " experienced " + cnt + " outages.";
  }

  if (expected && q.answer !== expected) {
    wrong++;
    console.log("Q" + (i+1) + " FIX: [" + q.answer.substring(0,70) + "] -> [" + expected.substring(0,70) + "]");
    return Object.assign({}, q, { answer: expected });
  }
  return q;
});

console.log("\nTotal wrong answers fixed:", wrong);
fs.writeFileSync(path.join(DATA,"eval_questions.json"), JSON.stringify(newQ, null, 2), "utf8");
console.log("Saved", newQ.length, "corrected questions to eval_questions.json");
